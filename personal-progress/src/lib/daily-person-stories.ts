const firstDay = Date.UTC(2026, 10, 10);
const dayMs = 86_400_000;

export function personStoryForDate(date: string) {
  const day = (Date.parse(`${date}T00:00:00Z`) - firstDay) / dayMs;
  const index = ((day % stories.length) + stories.length) % stories.length;
  return stories[index];
}
